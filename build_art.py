"""Bake pieces from the ECF wallet ASCII set into art-data.js for the landing page.

Reads the bundled 24-bit ANSI files in `art-source/`, crops each piece,
and writes a compact table the page draws on <canvas> (ascii-motion.js):

    rows   -- the character grid, one string per row, trailing spaces stripped
    color  -- run-length colour runs over the whole grid, row-major:
              "<palette letter><count>" pairs, "_" for blank cells

    python3 build_art.py              # rebuild art-data.js
    python3 build_art.py --src DIR    # read .ans files from another folder
"""
import argparse
import json
import pathlib
import re

HERE = pathlib.Path(__file__).resolve().parent
DEFAULT_SRC = HERE / "art-source"

# Same 8 colours as imagery.py's PAL. The page maps the letters back to hex.
PAL = {
    (255, 255, 255): "w", (255, 0, 0): "r", (0, 255, 0): "g", (0, 255, 255): "c",
    (255, 255, 0): "y", (255, 0, 255): "m", (0, 0, 255): "b", (255, 128, 0): "o",
}

# key -> (source piece, crop box x0, y0, x1, y1 in cells; None = whole grid)
PIECES = {
    "key":      ("12-key",      None),
    "ethscape": ("22-ethscape", None),
}

SGR = re.compile(r"\x1b\[([0-9;]*)m")


def parse_ans(path):
    """Return (chars, colours) as lists of lists; colour is a palette letter or ' '."""
    chars, cols = [], []
    for line in path.read_text(encoding="utf-8").split("\n"):
        rc, rf = [], []
        cur = "w"
        pos = 0
        for m in SGR.finditer(line):
            for ch in line[pos:m.start()]:
                rc.append(ch)
                rf.append(" " if ch == " " else cur)
            pos = m.end()
            params = m.group(1)
            if params.startswith("38;2;"):
                r, g, b = (int(v) for v in params.split(";")[2:5])
                cur = PAL.get((r, g, b), "w")
            elif params in ("", "0"):
                cur = "w"
        for ch in line[pos:]:
            rc.append(ch)
            rf.append(" " if ch == " " else cur)
        chars.append(rc)
        cols.append(rf)
    return chars, cols


def grid_size(name):
    # imagery pieces are 240x75 (8x16 px cells) or 320x100 (6x12 px cells)
    return (240, 75) if name.split("-")[0] in {"10", "12", "13", "17", "19", "21"} else (320, 100)


def bake(src, name, box):
    chars, cols = parse_ans(src / f"{name}.ans")
    gw, gh = grid_size(name)
    x0, y0, x1, y1 = box or (0, 0, gw, gh)
    rows, runs = [], []
    last, count = None, 0
    for y in range(y0, y1):
        rc = chars[y] if y < len(chars) else []
        rf = cols[y] if y < len(cols) else []
        row = []
        for x in range(x0, x1):
            ch = rc[x] if x < len(rc) else " "
            fg = rf[x] if x < len(rf) else " "
            row.append(ch)
            key = "_" if ch == " " else fg
            if key == last:
                count += 1
            else:
                if last is not None:
                    runs.append(f"{last}{count}")
                last, count = key, 1
        rows.append("".join(row).rstrip())
    runs.append(f"{last}{count}")
    return {"cols": x1 - x0, "rows": y1 - y0, "chars": rows, "color": "".join(runs)}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--src", type=pathlib.Path, default=DEFAULT_SRC)
    args = ap.parse_args()
    data = {key: bake(args.src, name, box) for key, (name, box) in PIECES.items()}
    out = HERE / "art-data.js"
    body = json.dumps(data, ensure_ascii=False, separators=(",", ":"))
    out.write_text(
        "// Generated by build_art.py from the ECF wallet ASCII set. Do not edit by hand.\n"
        f"window.ECF_ART={body};\n",
        encoding="utf-8",
    )
    for key, d in data.items():
        print(f"{key:12s} {d['cols']:3d}x{d['rows']:<3d} {PIECES[key][0]}")
    print(f"wrote {out.name}: {out.stat().st_size / 1024:.0f} KB")


if __name__ == "__main__":
    main()
